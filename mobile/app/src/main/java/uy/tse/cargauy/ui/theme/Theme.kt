/** Colores de la barra superior, que material no trae como rol propio. */
@Immutable
data class ColoresBarra(val fondo: Color, val contenido: Color)

val LocalColoresBarra = staticCompositionLocalOf { ColoresBarra(Color.Unspecified, Color.Unspecified) }

// en claro la barra lleva el color de la marca; en oscuro una superficie apenas mas clara que el fondo,
// porque una barra de color brillante encandila y pasa a ser lo que mas llama la atencion de la pantalla
private fun coloresBarra(esquema: ColorScheme, darkTheme: Boolean) =
    if (darkTheme) ColoresBarra(fondo = esquema.surfaceContainer, contenido = esquema.onSurface)
    else ColoresBarra(fondo = esquema.primary, contenido = esquema.onPrimary)

@Composable
fun CargaUYTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color is available on Android 12+
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    CompositionLocalProvider(LocalColoresBarra provides coloresBarra(colorScheme, darkTheme)) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
